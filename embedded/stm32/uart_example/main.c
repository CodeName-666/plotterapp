#include "main.h"
#include "../../common/plotter.h"
#include <string.h>

#define SAMPLE_RATE_MS 50  // 20 Hz

UART_HandleTypeDef huart2;
ADC_HandleTypeDef hadc1;

Plotter plotter;
uint32_t lastSample = 0;

// Send function for UART
void uartSend(const char* data, uint16_t length) {
    HAL_UART_Transmit(&huart2, (uint8_t*)data, length, 100);
}

void SystemClock_Config(void);
static void MX_GPIO_Init(void);
static void MX_USART2_UART_Init(void);
static void MX_ADC1_Init(void);

int main(void) {
    HAL_Init();
    SystemClock_Config();
    MX_GPIO_Init();
    MX_USART2_UART_Init();
    MX_ADC1_Init();

    // Initialize plotter with timestamp
    plotter_init(&plotter, uartSend, 1);
    plotter_set_start_time(&plotter, HAL_GetTick());

    // Send startup message
    const char* msg = "# STM32 UART PlotterApp Example\r\n";
    HAL_UART_Transmit(&huart2, (uint8_t*)msg, strlen(msg), 100);

    while (1) {
        uint32_t currentTime = HAL_GetTick();

        if (currentTime - lastSample >= SAMPLE_RATE_MS) {
            lastSample = currentTime;

            // Read ADC
            HAL_ADC_Start(&hadc1);
            if (HAL_ADC_PollForConversion(&hadc1, 10) == HAL_OK) {
                uint32_t rawValue = HAL_ADC_GetValue(&hadc1);
                float voltage = (rawValue / 4095.0f) * 3.3f;

                // Send data point (channel 0)
                plotter_send(&plotter, 0, voltage, currentTime);
            }
            HAL_ADC_Stop(&hadc1);
        }

        // Small delay to prevent blocking
        HAL_Delay(1);
    }
}

